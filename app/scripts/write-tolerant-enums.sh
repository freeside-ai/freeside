#!/usr/bin/env bash
# write-tolerant-enums.sh — writes app/Sources/FreesideAPI/TolerantEnums.swift
# from the generated client: one UnknownTolerantEnum conformance for every
# generated String enum that declares `case unknown = "unknown"`, and the list
# of those types for the test that checks each one decodes tolerantly.
#
# generate-api-client.sh runs it after the OpenAPI generator, and its output
# is one of that script's drift-checked outputs. The generator nests a
# property's inline enum inside its schema's struct, so the script recovers
# each enum's qualified name from brace depth. It strips doc comments and
# string literals first, so a brace in either can't shift the nesting.
set -euo pipefail

app_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
types="$app_dir/Sources/FreesideAPI/GeneratedSources/Types.swift"
out="$app_dir/Sources/FreesideAPI/TolerantEnums.swift"

names=$(awk '
    /^[[:space:]]*\/\/\// { next }
    {
        line = $0
        if (line ~ /^[[:space:]]*case unknown = "unknown"[[:space:]]*$/ && top > 0 && rawString[top]) {
            qualified = name[1]
            for (i = 2; i <= top; i++) qualified = qualified "." name[i]
            print qualified
        }
        gsub(/"([^"\\]|\\.)*"/, "", line)
        if (match(line, /(struct|enum) [A-Za-z_][A-Za-z0-9_]*/) && index(line, "{") > 0) {
            declared = substr(line, RSTART, RLENGTH)
            sub(/^(struct|enum) /, "", declared)
            pending = declared
            pendingString = (line ~ /enum [A-Za-z_][A-Za-z0-9_]*: String,/)
        } else {
            pending = ""
        }
        n = length(line)
        for (c = 1; c <= n; c++) {
            ch = substr(line, c, 1)
            if (ch == "{") {
                depth++
                if (pending != "") {
                    top++
                    name[top] = pending
                    rawString[top] = pendingString
                    opened[top] = depth
                    pending = ""
                }
            } else if (ch == "}") {
                if (top > 0 && opened[top] == depth) top--
                depth--
            }
        }
    }
' "$types")

if [[ -z $names ]]; then
    echo "write-tolerant-enums.sh: no generated enum declares case unknown" >&2
    exit 1
fi

{
    echo '// Generated by app/scripts/write-tolerant-enums.sh from'
    echo '// GeneratedSources/Types.swift. Do not edit; run'
    echo '// app/scripts/generate-api-client.sh.'
    echo
    while IFS= read -r type; do
        echo "extension $type: UnknownTolerantEnum {}"
    done <<<"$names"
    echo
    echo "/// Every generated enum that decodes an undeclared value as \`unknown\`."
    echo 'public enum TolerantEnums {'
    echo '    public static let all: [any UnknownTolerantEnum.Type] = ['
    while IFS= read -r type; do
        echo "        $type.self,"
    done <<<"$names"
    echo '    ]'
    echo '}'
} >"$out"
