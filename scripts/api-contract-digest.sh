#!/usr/bin/env bash
# api-contract-digest.sh — the single source of the API contract identity.
#
# The contract digest is "sha256:" plus the lowercase hex SHA-256 of the
# exact bytes of api/openapi.yaml. It is written into two generated,
# compiled-in constants so neither the daemon nor the Swift client can
# drift from the spec:
#   daemon/internal/signet/contract_digest.go   (const APIContractDigest)
#   app/Sources/FreesideAPI/ContractDigest.swift (APIContract.digest)
#
# Beside the digest, both files carry the spec's compatibility level and
# floor, read from the `x-compatibility-level` and `x-compatibility-floor`
# lines under `info` (APIContractCompatibilityLevel and
# APIContractCompatibilityFloor in Go, APIContract.compatibilityLevel and
# APIContract.compatibilityFloor in Swift). The script fails when either
# line is missing, duplicated, or not a non-negative integer, or when the
# floor exceeds the level.
#
# The daemon reports all three on GET /health. The client decides from the
# level and floor whether it can talk to the daemon at all (#3109); the
# digest only names the daemon's contract for diagnosis.
#
# Usage:
#   api-contract-digest.sh            print the digest
#   api-contract-digest.sh --write    (re)write both generated constants
#   api-contract-digest.sh --check    fail if either generated constant is
#                                     stale, naming the file and the fix
#   api-contract-digest.sh --compatibility <spec>
#                                     print "<level> <floor>" from the
#                                     spec file's info, with the same
#                                     validation (the compat check reads
#                                     the merge base's spec this way)
#
# The `api` component's `digest` step (scripts/check.sh) runs --check, as
# does app/scripts/generate-api-client.sh's drift list, so CI fails when a
# spec change forgets to regenerate the constants.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
SPEC="$ROOT/api/openapi.yaml"
GO_FILE="$ROOT/daemon/internal/signet/contract_digest.go"
SWIFT_FILE="$ROOT/app/Sources/FreesideAPI/ContractDigest.swift"

sha256_hex() { # <file>; prints the lowercase hex SHA-256 of the file
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | cut -d' ' -f1
  elif command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$1" | cut -d' ' -f1
  else
    echo "api-contract-digest.sh: no sha256sum or shasum found" >&2
    exit 1
  fi
}

digest() { printf 'sha256:%s' "$(sha256_hex "$SPEC")"; }

# info_integer <spec> <key>: prints the value of the one `  <key>: <n>`
# line under `info`, failing on a missing, duplicated, or non-integer line.
info_integer() {
  local spec=$1 key=$2 lines count value
  lines=$(awk -v key="$key" '
    /^[^ #]/ { in_info = ($0 == "info:") }
    in_info && index($0, "  " key ":") == 1 { print }
  ' "$spec")
  if [ -z "$lines" ]; then
    echo "api-contract-digest.sh: $spec has no \`$key\` under info" >&2
    return 1
  fi
  count=$(printf '%s\n' "$lines" | wc -l | tr -d ' ')
  if [ "$count" -ne 1 ]; then
    echo "api-contract-digest.sh: $spec has $count \`$key\` lines under info" >&2
    return 1
  fi
  value=${lines#"  $key: "}
  if [ "$value" = "$lines" ] || ! [[ $value =~ ^(0|[1-9][0-9]{0,8})$ ]]; then
    echo "api-contract-digest.sh: \`$lines\` in $spec is not \`  $key: <non-negative integer>\`" >&2
    return 1
  fi
  printf '%s' "$value"
}

# compatibility <spec>: sets LEVEL and FLOOR from the spec, failing when
# the floor exceeds the level.
compatibility() {
  LEVEL=$(info_integer "$1" x-compatibility-level)
  FLOOR=$(info_integer "$1" x-compatibility-floor)
  if [ "$FLOOR" -gt "$LEVEL" ]; then
    echo "api-contract-digest.sh: x-compatibility-floor ($FLOOR) exceeds x-compatibility-level ($LEVEL) in $1" >&2
    return 1
  fi
}

go_contents() { # <digest> <level> <floor>
  cat <<EOF
// Code generated by scripts/api-contract-digest.sh; DO NOT EDIT.

package signet

// APIContractDigest identifies the api/openapi.yaml this daemon was built
// from: "sha256:" plus the lowercase hex SHA-256 of the spec's exact
// bytes. The daemon reports it on GET /health to name its contract.
// Regenerate with scripts/api-contract-digest.sh --write.
const APIContractDigest = "$1"

// APIContractCompatibilityLevel is the spec's x-compatibility-level: the
// count of changes that broke apps built before them. The daemon reports
// it on GET /health so a newer app can tell this daemon is too old for it.
const APIContractCompatibilityLevel = $2

// APIContractCompatibilityFloor is the spec's x-compatibility-floor: the
// lowest app compatibility level this daemon serves. The daemon reports it
// on GET /health so an older app can tell it is too old for this daemon;
// the daemon itself never refuses a client on version.
const APIContractCompatibilityFloor = $3
EOF
}

swift_contents() { # <digest> <level> <floor>
  cat <<EOF
// Code generated by scripts/api-contract-digest.sh; DO NOT EDIT.

/// Identity of the api/openapi.yaml this client was built from.
public enum APIContract {
    /// "sha256:" plus the lowercase hex SHA-256 of the spec's exact bytes.
    /// It names the contract for diagnosis; compatibility comes from the
    /// level and floor below, never from a digest difference.
    public static let digest = "$1"

    /// The spec's x-compatibility-level: the count of changes that broke
    /// apps built before them. A daemon whose reported floor is above it
    /// is too new for this app; a daemon whose reported level is below it
    /// is too old.
    public static let compatibilityLevel = $2

    /// The spec's x-compatibility-floor: the lowest app level a daemon
    /// built from this spec serves.
    public static let compatibilityFloor = $3
}
EOF
}

write() {
  local d
  d=$(digest)
  compatibility "$SPEC"
  go_contents "$d" "$LEVEL" "$FLOOR" >"$GO_FILE"
  swift_contents "$d" "$LEVEL" "$FLOOR" >"$SWIFT_FILE"
  echo "wrote $GO_FILE and $SWIFT_FILE ($d, level $LEVEL, floor $FLOOR)" >&2
}

check() {
  local d stale=0
  d=$(digest)
  compatibility "$SPEC"
  if ! diff -u <(cat "$GO_FILE" 2>/dev/null) <(go_contents "$d" "$LEVEL" "$FLOOR") >/dev/null 2>&1; then
    echo "stale: $GO_FILE" >&2
    stale=1
  fi
  if ! diff -u <(cat "$SWIFT_FILE" 2>/dev/null) <(swift_contents "$d" "$LEVEL" "$FLOOR") >/dev/null 2>&1; then
    echo "stale: $SWIFT_FILE" >&2
    stale=1
  fi
  if [ "$stale" -ne 0 ]; then
    echo "regenerate with: bash scripts/api-contract-digest.sh --write" >&2
    exit 1
  fi
  echo "contract digest constants match api/openapi.yaml ($d, level $LEVEL, floor $FLOOR)" >&2
}

case "${1-}" in
  "") digest ;;
  --write) write ;;
  --check) check ;;
  --compatibility)
    [ $# -eq 2 ] || { echo "usage: $(basename "$0") --compatibility <spec>" >&2; exit 2; }
    compatibility "$2"
    printf '%s %s\n' "$LEVEL" "$FLOOR"
    ;;
  *)
    echo "usage: $(basename "$0") [--write|--check|--compatibility <spec>]" >&2
    exit 2
    ;;
esac
